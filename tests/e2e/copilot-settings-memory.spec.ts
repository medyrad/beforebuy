import { mkdir } from 'node:fs/promises'
import { resolve } from 'node:path'
import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

// Never retain traces, videos or automatic failure screenshots of credential entry.
test.use({ trace: 'off', screenshot: 'off', video: 'off' })
for (const width of [1440, 390]) {
  test(`settings and two-conversation opt-in memory at ${width}`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/copilot')
    const settings = page.getByRole('button', { name: 'تنظیمات دستیار', exact: true })
    await settings.focus(); await page.keyboard.press('Enter')
    await expect(page.getByRole('heading', { name: 'تنظیمات دستیار' })).toBeVisible()
    await expect(page.getByText(/اتصال زنده مسدود است/)).toBeVisible()
    const key = page.getByLabel('کلید OpenAI', { exact: true })
    await key.fill('synthetic-browser-not-a-real-key-111')
    await page.getByRole('button', { name: 'ذخیرهٔ کلید', exact: true }).click()
    await expect(page.getByText('ذخیره‌شده؛ اعتبارسنجی نشده', { exact: true })).toBeVisible()
    await expect(key).toHaveValue('')
    await key.fill('synthetic-browser-not-a-real-key-222')
    await page.getByRole('button', { name: 'جایگزینی کلید', exact: true }).click()
    await expect(key).toHaveValue('')
    await expect(page.getByRole('button', { name: 'حذف کلید' })).toBeEnabled()
    await page.getByRole('button', { name: 'حذف کلید' }).click()
    await expect(page.getByText('کلیدی ذخیره نشده', { exact: true })).toBeVisible()
    await expect(page.getByLabel('مدل مستندشده')).toContainText('تأییدنشده برای حساب')
    const screenshots = resolve('../artifacts/screenshots')
    await mkdir(screenshots, { recursive: true })
    await page.screenshot({ path: resolve(screenshots, `copilot-phase11-settings-${width}.png`), fullPage: true })
    const audit = await new AxeBuilder({ page }).analyze()
    expect(audit.violations.filter(v => ['serious', 'critical'].includes(v.impact ?? ''))).toEqual([])

    await page.getByRole('button', { name: 'شناخت من', exact: true }).click()
    await page.getByRole('button', { name: 'فعال‌کردن حافظه با رضایت من' }).click()
    await expect(page.getByText('حافظه روشن است.', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'میز خرید', exact: true }).click()
    const firstCreated = page.waitForResponse(r => r.url().endsWith('/conversations') && r.request().method() === 'POST')
    await page.getByRole('button', { name: 'گفت‌وگوی تازه', exact: true }).last().click()
    expect((await firstCreated).status()).toBe(201)
    if (width === 390) await page.getByRole('button', { name: 'میز انتخاب', exact: true }).click()
    await expect(page.getByText('مخاطب نامعلوم', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'ویرایش brief' }).click()
    await page.getByLabel('دسته', { exact: true }).fill('electronics')
    await page.getByRole('combobox', { name: 'مخاطب', exact: true }).selectOption('SELF')
    await page.getByRole('combobox', { name: 'قابل‌حمل بودن', exact: true }).selectOption('PREFERENCE')
    await page.getByRole('button', { name: 'ذخیره', exact: true }).click()
    await expect(page.getByRole('button', { name: 'ذخیره', exact: true })).not.toBeVisible()
    await page.getByRole('button', { name: 'تأیید brief برای پژوهش' }).click()
    await page.getByRole('button', { name: 'پیشنهاد ترجیح برای شناخت من' }).click()
    await expect(page.getByText('پیشنهادها در شناخت من منتظر بررسی شما هستند.')).toBeVisible()
    await page.getByRole('button', { name: 'شناخت من', exact: true }).click()
    await page.getByRole('button', { name: 'تأیید ترجیح' }).click()
    await expect(page.getByText('تأییدشده برای پیشنهاد در خرید بعدی')).toBeVisible()
    await page.getByRole('button', { name: 'میز خرید', exact: true }).click()
    if (width === 390) await page.getByRole('button', { name: 'گفت‌وگو', exact: true }).click()
    const secondCreated = page.waitForResponse(r => r.url().endsWith('/conversations') && r.request().method() === 'POST')
    await page.getByRole('button', { name: 'گفت‌وگوی تازه', exact: true }).last().click()
    expect((await secondCreated).status()).toBe(201)
    if (width === 390) await page.getByRole('button', { name: 'میز انتخاب', exact: true }).click()
    await expect(page.getByText('مخاطب نامعلوم', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'ویرایش brief' }).click()
    await page.getByLabel('دسته', { exact: true }).fill('electronics')
    await page.getByRole('combobox', { name: 'مخاطب', exact: true }).selectOption('SELF')
    await page.getByRole('button', { name: 'ذخیره', exact: true }).click()
    await expect(page.getByRole('button', { name: 'ذخیره', exact: true })).not.toBeVisible()
    await page.getByRole('button', { name: 'استفاده در این خرید' }).click()
    await expect(page.getByText('brief نسخهٔ ۲', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'ویرایش brief' }).click()
    await expect(page.getByRole('combobox', { name: 'انتظار شما: قابل‌حمل بودن', exact: true })).toHaveValue('yes')
    await page.getByRole('combobox', { name: 'انتظار شما: قابل‌حمل بودن', exact: true }).selectOption('no')
    await page.getByRole('button', { name: 'ذخیره', exact: true }).click()
    await expect(page.getByRole('button', { name: 'ذخیره', exact: true })).not.toBeVisible()
    await page.getByRole('button', { name: 'ویرایش brief' }).click()
    await expect(page.getByRole('combobox', { name: 'انتظار شما: قابل‌حمل بودن', exact: true })).toHaveValue('no')
    await page.getByRole('button', { name: 'شناخت من', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'قابل‌حمل بودن: بله — خودم' })).toBeVisible()
    await page.screenshot({ path: resolve(screenshots, `copilot-phase11-memory-${width}.png`), fullPage: true })
    await page.evaluate(() => { document.documentElement.style.zoom = '2' })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const zoomAudit = await new AxeBuilder({ page }).analyze()
    expect(zoomAudit.violations.filter(v => ['serious', 'critical'].includes(v.impact ?? ''))).toEqual([])
    await page.evaluate(() => { document.documentElement.style.zoom = '' })
    await page.getByRole('button', { name: 'حذف ترجیح', exact: true }).click()
    await expect(page.getByText(/هنوز ترجیحی ذخیره نشده/)).toBeVisible()
    await page.goto('/')
    await expect(page.getByRole('heading', { name: /قبل از خرید/ })).toBeVisible()
  })
}
