test('long thread/history, detached stream, zoom, and preserved legacy reports', async ({ page }) => {
  test.setTimeout(180000)
  await page.setViewportSize({ width: 1280, height: 720 })
  await send(page, 'بودجه‌ام ۱۵ میلیون تومان است')
  for (let i = 0; i < 14; i++) await send(page, `پیام آزمایشی بلند ${i}: ${'این متن فقط دادهٔ مصنوعی آزمون خوانایی و پیمایش است. '.repeat(6)}`)
  await reachable(page)
  await page.locator('.thread').evaluate(el => { el.scrollTop = 0; el.dispatchEvent(new Event('scroll')) })
  const before = await page.locator('.thread').evaluate(el => el.scrollTop)
  await page.getByRole('button', { name: 'تنظیمات دستیار', exact: true }).click()
  await page.getByRole('button', { name: 'میز خرید', exact: true }).click()
  expect(await page.locator('.thread').evaluate(el => el.scrollTop)).toBe(before)
  // Real accepted operation, but delay only the browser delivery to deterministically switch mid-stream.
  await page.route('**/operations/*/events', async route => { await new Promise(resolve => setTimeout(resolve, 1200)); await route.continue() })
  await page.getByRole('textbox', { name: 'پیام شما' }).fill('پاسخ متعلق به گفت‌وگوی قدیمی')
  await page.getByRole('button', { name: 'ارسال پیام' }).click()
  await expect(page.getByRole('button', { name: 'توقف تولید' })).toBeVisible()
  await reachable(page, 'توقف تولید')
  await page.getByRole('button', { name: 'خرید تازه', exact: true }).click()
  await page.getByRole('textbox', { name: 'پیام شما' }).fill('پیش‌نویس گفت‌وگوی تازه')
  await page.waitForTimeout(1500)
  await expect(page.locator('.message')).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: 'پیام شما' })).toHaveValue('پیش‌نویس گفت‌وگوی تازه')
  await page.unrouteAll({ behavior: 'wait' })
  for (let i = 0; i < 52; i++) await command(page, '/api/v1/conversations', { title: `گفت‌وگوی مصنوعی تاریخچه ${i}` })
  await page.getByRole('button', { name: 'گفت‌وگوهای من', exact: true }).click()
  await expect(page.locator('.history-open')).toHaveCount(50)
  await page.getByRole('button', { name: 'بارگذاری بیشتر' }).click()
  await expect(page.locator('.history-open')).toHaveCount(53)
  await page.getByRole('button', { name: 'پاک‌کردن همهٔ گفت‌وگوها' }).click()
  await page.getByRole('button', { name: 'بله، حذف شود' }).click()
  await expect(page.getByText(/هنوز گفت‌وگویی ندارید/)).toBeVisible()
  await page.getByRole('button', { name: 'بستن تاریخچه' }).click()
  await page.evaluate(() => { document.documentElement.style.zoom = '2' })
  await reachable(page)
  expect(await seriousAccessibilityViolations(page)).toEqual([])
  await page.evaluate(() => { document.documentElement.style.zoom = '' })
  await page.getByRole('link', { name: 'نسخهٔ قبلی', exact: true }).click()
  await completeAnalysis(page, { product: 'گزارش مصنوعی برای حفظ مسیر قبلی' })
  const url = new URL(page.url())
  await page.goto(`/?analysis=${url.searchParams.get('analysis')}`)
  await expect(page.getByRole('heading', { name: 'جمع‌بندی برای تصمیم شما' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'جمع‌بندی برای تصمیم شما' })).toBeVisible()
})
