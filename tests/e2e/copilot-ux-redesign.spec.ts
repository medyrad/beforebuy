async function send(page: Page, text: string) {
  const count = await page.locator('.message.assistant:not(.provisional)').count()
  await page.getByRole('textbox', { name: 'پیام شما' }).fill(text)
  await page.getByRole('button', { name: 'ارسال پیام' }).click()
  await expect(page.locator('.message.assistant:not(.provisional)')).toHaveCount(count + 1, { timeout: 20000 })
}
async function reachable(page: Page, name = 'ارسال پیام') {
  const box = await page.getByRole('button', { name, exact: true }).boundingBox()
  expect(box).not.toBeNull()
  expect(box!.y).toBeGreaterThanOrEqual(0)
  expect(box!.y + box!.height).toBeLessThanOrEqual(page.viewportSize()!.height)
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
}
async function command(page: Page, path: string, data: unknown = {}, method = 'POST') {
  return page.evaluate(async ({ path, data, method }) => {
    const token = document.cookie.split('; ').find(i => i.startsWith('csrftoken='))?.split('=')[1] ?? ''
    const r = await fetch(path, { method, headers: { 'Content-Type': 'application/json', 'X-CSRFToken': decodeURIComponent(token) }, body: JSON.stringify(data) })
    if (!r.ok) throw new Error(`synthetic command ${r.status}`)
    return r.status === 204 ? null : r.json()
  }, { path, data, method })
}

